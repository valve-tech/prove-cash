/**
 * Write the contract ABIs into TypeScript, from what the compiler actually produced.
 *
 * The ABI used to be typed out by hand here. When the settlement contract changed, six entries
 * went stale and nothing noticed: `tsc` cannot read a JSON import as literal types, so the app
 * still compiled, CI still passed, and every escrow and fill call would have failed on chain.
 * A generated `as const` array makes a wrong function name a compile error instead.
 *
 *   node scripts/gen-abi.mjs            write sdk/src/abi.ts
 *   node scripts/gen-abi.mjs --check    exit 1 if it is out of date, for CI
 *
 * Run `forge build` in `contracts/` first: this reads the compiler's own output.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseAbiItem } from 'viem'

const here = dirname(fileURLToPath(import.meta.url))
const out = join(here, '..', '..', 'contracts', 'out')
const target = join(here, '..', 'src', 'abi.ts')

/** The contracts the SDK talks to, and the name each ABI takes in TypeScript. */
const CONTRACTS = [
  ['ProveSettlement', 'SETTLEMENT_ABI'],
  ['ProveRelayer', 'RELAYER_ABI'],
  ['ProveBatchExecutor', 'BATCH_EXECUTOR_ABI'],
  ['ProveExecutor', 'EXECUTOR_ABI'],
  ['RfqVenue', 'RFQ_VENUE_ABI'],
  ['FeeDefaults', 'FEE_DEFAULTS_ABI'],
  ['ProveReader', 'READER_ABI'],
]

/** Keep only what a caller can reach. Constructors and the like are noise in a client ABI. */
const wanted = (e) => e.type === 'function' || e.type === 'event' || e.type === 'error'

const body = CONTRACTS.map(([contract, name]) => {
  const artifact = JSON.parse(readFileSync(join(out, `${contract}.sol`, `${contract}.json`), 'utf8'))
  const abi = artifact.abi.filter(wanted)
  return `/** ${contract}, straight from the compiler. Do not edit — see scripts/gen-abi.mjs. */\nexport const ${name} = ${JSON.stringify(abi, null, 2)} as const\n`
}).join('\n')

const file = `// Generated by scripts/gen-abi.mjs. Do not edit.\n//\n// The compiler is the only author of this file. CI regenerates it and fails on a diff, so an\n// ABI here can never drift from the contract it claims to describe.\n\n${body}`

/** Blank comments and the inside of every string, keeping each character's position. */
function blankNonCode(text) {
  const out = text.split('')
  const blank = (i) => {
    if (out[i] !== '\n') out[i] = ' '
  }
  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (c === '/' && text[i + 1] === '/') {
      while (i < text.length && text[i] !== '\n') blank(i++)
    } else if (c === '/' && text[i + 1] === '*') {
      const close = text.indexOf('*/', i + 2)
      const end = close < 0 ? text.length : close + 2
      while (i < end) blank(i++)
    } else if (c === '"' || c === "'" || c === '`') {
      // Blank the body so a brace inside a string cannot unbalance the scan below. A template's
      // own `${` and `}` sit in the body too, so they go together and the count stays even.
      i++
      while (i < text.length && text[i] !== c) {
        if (text[i] === '\\') blank(i++)
        blank(i++)
      }
    }
  }
  return out.join('')
}

/**
 * The `abi:` of the object literal that holds the property at `at`, or null when it names none.
 *
 * The value comes back as written — `SETTLEMENT_ABI`, `erc20Abi` and `[]` are all possible — so
 * the caller decides what counts as ours. Read `code` from `blankNonCode`, not from the file.
 */
function abiBeside(code, at) {
  // Walk back to the brace that opens the enclosing object literal.
  let depth = 0
  let i = at
  while (i-- > 0) {
    const c = code[i]
    if (c === '}' || c === ')' || c === ']') depth++
    else if (c === '{' || c === '(' || c === '[') {
      if (depth === 0) break
      depth--
    }
  }
  if (i < 0 || code[i] !== '{') return null
  // Then read that literal's own properties, and nothing nested inside them.
  depth = 0
  for (let j = i + 1; j < code.length; j++) {
    const c = code[j]
    if (c === '{' || c === '(' || c === '[') depth++
    else if (c === ')' || c === ']') depth--
    else if (c === '}') {
      if (depth === 0) return null
      depth--
    } else if (depth === 0 && /^abi\s*:/.test(code.slice(j, j + 8)) && !/[\w$.]/.test(code[j - 1] ?? '')) {
      return code.slice(j).replace(/^abi\s*:/, '').match(/^\s*([^,\n}]*)/)[1].trim()
    }
  }
  return null
}

/**
 * Every `functionName` aimed at one of our contracts must name a real function.
 *
 * TypeScript will not do this for us. `writeContract` is called through `as never` because the
 * wallet client is deliberately loosely typed, and viem's inference degrades on an ABI this size
 * anyway — six stale names once passed `tsc` cleanly. So check the strings against the compiler's
 * own output instead, and let CI fail on a name no contract answers to.
 *
 * A call site says which contract it means by the `abi:` next to the `functionName:`, and that is
 * what decides whether the check applies. The SDK also calls ERC-20 tokens, Multicall3 and PulseX,
 * and their functions will never appear in our artifacts. A list of excused names cannot tell the
 * two apart: the old list excused `deposit`, `name` and `factory` everywhere, so a typo in one of
 * those on our own settlement contract — exactly the bug this check exists to find — went through.
 *
 * A call site that names no ABI of its own stays ours to check. `callFor` in settlement.ts returns
 * `{ functionName, args }` and lets `executeFills` supply `SETTLEMENT_ABI`, and those six names are
 * the ones that went stale before. Skipping them would leave the check with nothing to guard.
 */
const repo = join(here, '..', '..')
const rel = (p) => (p.startsWith(repo) ? p.slice(repo.length + 1) : p)

/**
 * A hand-written signature for one of our functions must match the compiler's.
 *
 * The name check above cannot see a wrong SHAPE. A hand-written signature that declares one
 * return where the contract has two names a real function and decodes the wrong thing: viem
 * reads the first word as the whole answer. One did exactly that on a `(bool, uint256)` getter
 * and printed the boolean as an amount. That is a silently wrong number, which is the worst kind.
 *
 * The unit is the `parseAbi([...])` BLOCK, not the line, because a name alone cannot say which
 * contract is meant. Three scripts declare WETH9's `deposit()` for WPLS, and our settlement has a
 * `deposit(Intent,uint256)` — same name, different contract, and comparing them is noise.
 *
 * So a block is ours when it names at least one function of ours that is not part of a standard
 * interface, and then EVERY signature in it is checked, `deposit` included. The list below only
 * decides whether a block is ours; it never excuses a mismatch inside one that is. That is the
 * opposite of the excused-names list this file used to carry on the name check, which let a typo
 * on our own settlement through — see `checkCallSites`.
 */
const STANDARD = new Set([
  'name', 'symbol', 'decimals', 'totalSupply', 'balanceOf', 'transfer', 'transferFrom', 'approve',
  'allowance', 'deposit', 'withdraw', 'owner', 'nonces', 'permit', 'DOMAIN_SEPARATOR',
  'transferOwnership', 'factory', 'token0', 'token1', 'getReserves', 'sync', 'mint', 'burn',
  // `claim` is `deposit` all over again. The settlement grew a `claim(address,address)` when the
  // fee became a booking, and four scripts already declare `FaucetToken.claim()` for the testnet
  // drip. Same name, different contract. This only stops a faucet block being read as ours; a
  // block that also names something of ours still has its `claim` checked.
  'claim',
])

function checkSignatures(sources) {
  const shape = (e) => {
    const t = (xs) => (xs ?? []).map((x) => (x.components ? `(${t(x.components)})` : x.type)).join(',')
    return `(${t(e.inputs)})->(${t(e.outputs)})`
  }
  const wanted = new Map()
  for (const [contract] of CONTRACTS) {
    const artifact = JSON.parse(readFileSync(join(out, `${contract}.sol`, `${contract}.json`), 'utf8'))
    for (const e of artifact.abi) {
      if (e.type !== 'function') continue
      if (!wanted.has(e.name)) wanted.set(e.name, new Set())
      wanted.get(e.name).add(shape(e))
    }
  }

  const wrong = []
  let compared = 0
  let skipped = 0
  for (const { p, raw } of sources) {
    for (const block of raw.matchAll(/parseAbi\(\[([\s\S]*?)\]\)/g)) {
      const items = [...block[1].matchAll(/'(function [A-Za-z0-9_]+\([^']*)'/g)].map((m) => m[1])
      const named = items.map((sig) => sig.slice('function '.length).split('(')[0])
      // Ours when something in here is distinctly ours.
      if (!named.some((n) => wanted.has(n) && !STANDARD.has(n))) {
        skipped++
        continue
      }
      for (const sig of items) {
        const name = sig.slice('function '.length).split('(')[0]
        const want = wanted.get(name)
        if (!want) continue
        let item
        try {
          item = parseAbiItem(sig)
        } catch {
          continue
        }
        compared++
        const got = shape(item)
        if (!want.has(got)) {
          wrong.push(`${rel(p)}: ${name} is written ${got}, the contract has ${[...want].join(' or ')}`)
        }
      }
    }
  }

  if (wrong.length) {
    console.error('These hand-written signatures disagree with the compiler:')
    for (const w of wrong) console.error(`  ${w}`)
    console.error('Import the generated ABI instead of writing the signature out.')
    process.exit(1)
  }
  console.log(`signatures check out (${compared} hand-written against the compiler, ${skipped} blocks on other contracts)`)
}

function checkCallSites() {
  const names = new Set()
  for (const [contract] of CONTRACTS) {
    const artifact = JSON.parse(readFileSync(join(out, `${contract}.sol`, `${contract}.json`), 'utf8'))
    for (const e of artifact.abi) if (e.type === 'function') names.add(e.name)
  }

  const src = join(here, '..', 'src')
  const generated = join(src, 'abi.ts')
  const files = []
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const p = join(dir, entry.name)
      if (entry.isDirectory()) walk(p)
      // Only the generated file is exempt, and by its path. Matching on the bare name also let
      // `solver/abi.ts` off, and its three settlement calls went unchecked for months.
      else if (/\.tsx?$/.test(entry.name) && p !== generated) files.push(p)
    }
  }
  walk(src)

  // The app's scripts call our contracts too, and they were never checked. Six of them once
  // hand-wrote an ABI while the generated one sat unused, and one of those declared a function
  // with a single return where the contract had two — so the decoder read a boolean as the
  // amount and printed a nonsense number above a prompt to act on it.
  const appScripts = join(here, '..', '..', 'app', 'scripts')
  if (existsSync(appScripts)) walk(appScripts)

  // And the web app itself. Its hooks and pages call the settlement through the SDK's ABI, and
  // a renamed function would fail only in a user's browser. `.tsx` counts: components call too.
  const appSrc = join(here, '..', '..', 'app', 'src')
  if (existsSync(appSrc)) walk(appSrc)

  const sources = files.map((p) => ({ p, raw: readFileSync(p, 'utf8') }))

  // An ABI is ours when it comes from the generated file, whatever name it goes by. `solver/abi.ts`
  // re-exports one, so follow plain aliases until the set stops growing.
  const ours = new Set(CONTRACTS.map(([, name]) => name))
  for (let grew = true; grew; ) {
    grew = false
    for (const { raw } of sources) {
      for (const m of raw.matchAll(/\b(?:const|let|var)\s+([A-Za-z0-9_$]+)\s*=\s*([A-Za-z0-9_$]+)\b/g)) {
        if (ours.has(m[2]) && !ours.has(m[1])) {
          ours.add(m[1])
          grew = true
        }
      }
    }
  }

  const bad = []
  let checked = 0
  let foreign = 0
  for (const { p, raw } of sources) {
    const code = blankNonCode(raw)
    for (const m of raw.matchAll(/functionName: '([A-Za-z0-9_]+)'/g)) {
      const abi = abiBeside(code, m.index)
      if (abi !== null && !ours.has(abi)) {
        foreign++
        continue
      }
      checked++
      if (!names.has(m[1])) bad.push(`${rel(p)}: ${m[1]}`)
    }
  }

  checkSignatures(sources)

  if (bad.length) {
    console.error('These call sites name a function no contract of ours has:')
    for (const b of bad) console.error(`  ${b}`)
    console.error('If the call goes to a contract we do not compile, give it that contract\u2019s own abi.')
    process.exit(1)
  }
  console.log(`call sites check out (${checked} against our ${names.size} functions, ${foreign} on other contracts)`)
}

if (process.argv.includes('--check')) {
  checkCallSites()
  const current = (() => {
    try {
      return readFileSync(target, 'utf8')
    } catch {
      return ''
    }
  })()
  if (current !== file) {
    console.error('src/abi.ts is out of date. Run: npm run gen:abi')
    process.exit(1)
  }
  console.log('src/abi.ts matches the compiled contracts')
} else {
  writeFileSync(target, file)
  console.log(`wrote ${target}`)
}
