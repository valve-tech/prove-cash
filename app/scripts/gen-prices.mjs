#!/usr/bin/env node
/**
 * Real hourly prices for the landing page's hero chart, baked into the bundle.
 *
 * The hero used to draw a seeded random walk. It looked like a market from a distance and like a
 * generated curve up close, because a mean-reverting mulberry32 path has none of the clustering
 * and none of the jumps a real tape has. Real data fixes that for free.
 *
 * Generated rather than fetched at runtime, for three reasons. The landing page must not make a
 * network call to draw its hero — a rate limit or an outage would leave a blank frame above the
 * fold. CoinGecko's free tier has no key and no CORS guarantee, so a browser fetch is not
 * something to depend on. And a build-time file is reviewable: you can read exactly what the page
 * will draw.
 *
 * Run `npm run gen:prices` to refresh. There is no `--check` mode on purpose: prices move, so a
 * check that fails when they have would fail every day and mean nothing.
 */

import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'landing', 'prices.ts')

/**
 * The pool the hero draws from. Ethereum mainnet addresses, because the logos come from
 * gib.show's `eip155-1` set and these are the marks a reader anywhere will recognise.
 *
 * Two stablecoins are in the pool so a pair can settle into one. The page rejects a
 * stable-to-stable draw, which would plot a flat line and animate nothing.
 */
const TOKENS = [
  { symbol: 'WETH', id: 'ethereum', address: '0xC02aaA39b223FE8D0A0e5C4F27eAD9083C756Cc2', decimals: 18, stable: false },
  { symbol: 'WBTC', id: 'wrapped-bitcoin', address: '0x2260FAC5E5542a773Aa44fBCfeDf7C193bc2C599', decimals: 8, stable: false },
  { symbol: 'LINK', id: 'chainlink', address: '0x514910771AF9Ca656af840dff83E8264EcF986CA', decimals: 18, stable: false },
  { symbol: 'UNI', id: 'uniswap', address: '0x1f9840a85d5aF5bf1D1762F925BDADdC4201F984', decimals: 18, stable: false },
  { symbol: 'AAVE', id: 'aave', address: '0x7Fc66500c84A76Ad7e9c93437bFc5Ac33E2DDaE9', decimals: 18, stable: false },
  { symbol: 'USDC', id: 'usd-coin', address: '0xA0b86991c6218b36c1d19D4a2e9Eb0cE3606eB48', decimals: 6, stable: true },
  { symbol: 'DAI', id: 'dai', address: '0x6B175474E89094C44Da98b954EedeAC495271d0F', decimals: 18, stable: true },
]

const DAYS = 7
const HOUR = 3_600_000

async function series(id) {
  const url = `https://api.coingecko.com/api/v3/coins/${id}/market_chart?vs_currency=usd&days=${DAYS}&interval=hourly`
  // The free tier throttles hard and answers 429 without a Retry-After. Back off and try again
  // rather than writing a file that is missing a token.
  let res
  for (let attempt = 0; attempt < 6; attempt++) {
    res = await fetch(url, { headers: { accept: 'application/json' } })
    if (res.status !== 429) break
    const wait = 15_000 * (attempt + 1)
    process.stderr.write(`429, waiting ${wait / 1000}s … `)
    await new Promise((r) => setTimeout(r, wait))
  }
  if (!res.ok) throw new Error(`${id}: HTTP ${res.status}`)
  const body = await res.json()
  if (!Array.isArray(body.prices) || body.prices.length === 0) throw new Error(`${id}: no prices`)
  // Snap to the hour. Different coins report a few seconds apart, and the ratio of two series is
  // only meaningful when both samples name the same hour.
  const byHour = new Map()
  for (const [ms, price] of body.prices) byHour.set(Math.round(ms / HOUR) * HOUR, price)
  return byHour
}

async function main() {
  const fetched = []
  for (const token of TOKENS) {
    // Sequential, with a pause. The free tier answers about 10 calls a minute and a 429 here
    // would write a half-empty file.
    process.stderr.write(`${token.symbol} … `)
    fetched.push({ token, byHour: await series(token.id) })
    process.stderr.write('ok\n')
    await new Promise((r) => setTimeout(r, 8000))
  }

  // Only hours every token reported. A missing hour in one series would shift every later sample
  // in that series against the others and bend a ratio that never moved.
  let hours = [...fetched[0].byHour.keys()]
  for (const { byHour } of fetched) hours = hours.filter((h) => byHour.has(h))
  hours.sort((a, b) => a - b)
  if (hours.length < 48) throw new Error(`only ${hours.length} shared hours`)

  const rows = fetched.map(({ token, byHour }) => ({
    ...token,
    usd: hours.map((h) => byHour.get(h)),
  }))

  const from = new Date(hours[0]).toISOString().slice(0, 16).replace('T', ' ')
  const to = new Date(hours[hours.length - 1]).toISOString().slice(0, 16).replace('T', ' ')

  const body = `/**
 * Real hourly prices, generated by \`scripts/gen-prices.mjs\` from CoinGecko.
 *
 * ${hours.length} hours, ${from} to ${to} UTC. Every series names the same hours, so the ratio of
 * any two of them is a real exchange rate over a real week.
 *
 * Do not edit. Run \`npm run gen:prices\` to refresh.
 */

export type PriceToken = {
  symbol: string
  /** Ethereum mainnet, for the logo. The hero is explaining a mechanism, not quoting a chain. */
  address: \`0x\${string}\`
  decimals: number
  /** True for a coin that holds a dollar. Two of them make a flat chart, so the pair draw skips it. */
  stable: boolean
  /** Hourly USD price, oldest first. */
  usd: readonly number[]
}

/** The window these prices cover, for the line that says so under the chart. */
export const SAMPLED = '${from.slice(0, 10)}'

export const PRICE_TOKENS: readonly PriceToken[] = [
${rows
  .map(
    (r) => `  {
    symbol: '${r.symbol}',
    address: '${r.address}',
    decimals: ${r.decimals},
    stable: ${r.stable},
    usd: [${r.usd.map((v) => Number(v.toPrecision(8))).join(', ')}],
  },`,
  )
  .join('\n')}
]
`

  writeFileSync(OUT, body)
  process.stderr.write(`wrote ${OUT}: ${rows.length} tokens x ${hours.length} hours\n`)
}

main().catch((e) => {
  process.stderr.write(`${e.message}\n`)
  process.exit(1)
})
